#!/usr/bin/env bash
# Builds FreeMyTablet.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-30 or newer).
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
# The tablet runs Android 9 to 11: compiling against android-30 keeps the newer APIs out of reach.
AJ=""
for p in $(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V -r); do
  v="$(basename "$(dirname "$p")" | sed 's/android-//')"
  if [ "$v" -le 30 ] 2>/dev/null; then AJ="$p"; break; fi
done
[ -n "$AJ" ] || AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-30\""; exit 1; }
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: put your city there (optional), then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude -23.31028)"
LON="$(number longitude -51.16278)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true

rm -rf out && mkdir -p out/gen/io/freemytablet out/classes
cat > out/gen/io/freemytablet/Config.java <<EOF
package io.freemytablet;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
}
EOF

# --- Version: from the tag (or from the environment, when the build is not in a git checkout)
VERSION="${FREE_MY_TABLET_VERSION:-}"
VERSION="${VERSION#v}"                       # the tag is "v1.1", the version is "1.1"
if [ -z "$VERSION" ]; then
  # The tag of the build (the version). The container may not own the checkout: git is told to trust it.
  VERSION="$( { git -c safe.directory='*' describe --tags --abbrev=0 2>/dev/null || true; } | sed 's/^v//')"
fi
[ -n "$VERSION" ] || VERSION="1.0"
# The version code has to grow: 1.1 -> 101, 1.10 -> 110, 2.0 -> 200
CODE="$(printf '%s' "$VERSION" | awk -F'[.-]' '{printf "%d%02d", $1+0, $2+0}')"
echo "Building version $VERSION (code $CODE)"

# --- Build
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 28 --target-sdk-version 30 --version-name "$VERSION" --version-code "$CODE" \
  -A app/assets -0 ttf
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ" \
  -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 28 --lib "$AJ" --output out $(find out/classes -name '*.class')
(cd out && zip -qj base.apk classes.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep freemytablet.keystore)
if [ ! -f freemytablet.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore freemytablet.keystore -alias freemytablet -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass freemytablet -keypass freemytablet -dname "CN=Free My Tablet" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks freemytablet.keystore --ks-pass pass:freemytablet --key-pass pass:freemytablet --out FreeMyTablet.apk out/aligned.apk
echo "Built FreeMyTablet.apk ($(du -h FreeMyTablet.apk | cut -f1)). Install: adb install -r FreeMyTablet.apk"
